def test_activity_detects_claims_and_prs():
    timeline = [
        {"event": "commented", "author_association": "NONE", "user": {"login": "someone"},
         "created_at": iso(3), "body": "Hi, I'd like to work on this!"},
        {"event": "commented", "author_association": "NONE", "user": {"login": "old"},
         "created_at": iso(60), "body": "can I take this?"},
        {"event": "cross-referenced", "source": {"issue": {"pull_request": {}, "state": "open",
                                                           "html_url": "https://x/pull/9"}}},
    ]
    gh = GitHub(transport=Fake({"repos/o/r/issues/1/timeline": timeline}))
    act = filters.activity(gh, "o/r", 1, claim_window_days=21, now=NOW)
    assert act["linked_open_prs"] == ["https://x/pull/9"]
    assert [c["by"] for c in act["recent_claims"]] == ["someone"]


