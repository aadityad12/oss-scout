def test_scale_bounds():
    assert score._scale(1, good=2, bad=60) == 1.0
    assert score._scale(60, good=2, bad=60) == 0.0
    assert 0 < score._scale(10, good=2, bad=60) < 1
    assert score._scale(None, good=2, bad=60) == 0.5


def test_is_outside_ignores_bots_and_members():
    assert score.is_outside({"author_association": "CONTRIBUTOR", "user": {"type": "User"}})
    assert not score.is_outside({"author_association": "MEMBER", "user": {"type": "User"}})
    assert not score.is_outside({"author_association": "NONE", "user": {"type": "Bot"}})


def test_measure_friendly_repo(monkeypatch):
    prs = [{"number": i, "author_association": "CONTRIBUTOR", "user": {"login": f"u{i}", "type": "User"},
            "created_at": iso(10), "merged_at": iso(8) if i % 5 else None} for i in range(10)]
    routes = {"repos/o/r": {"stargazers_count": 999, "language": "C++", "pushed_at": iso(1),
                            "owner": {"type": "Organization"}},
              "repos/o/r/pulls": prs}
    for p in prs:
        routes[f"repos/o/r/issues/{p['number']}/comments"] = [
            {"user": {"login": "maint", "type": "User"}, "author_association": "MEMBER",
             "created_at": iso(9.5)}]
    monkeypatch.setattr(policy, "fetch", lambda gh, repo: {"ai": "none", "evidence": "", "cla": False, "files": []})
    m = score.measure(GitHub(transport=Fake(routes)), "o/r", now=NOW)
    assert m["merge_rate"] == pytest.approx(0.8)
    assert m["median_days_to_merge"] == pytest.approx(2)
    assert m["median_hours_to_first_response"] == pytest.approx(12)
    assert m["confident"] and m["friendliness"] > 0.8


