def test_mentions():
    pr = {"title": "Fix crash", "body": "Fixes #123"}
    assert track._mentions(pr, "o/r", 123)
    assert not track._mentions(pr, "o/r", 12)
    assert track._mentions({"title": "x", "body": "see https://github.com/o/r/issues/7"}, "o/r", 7)
    assert not track._mentions({"title": "x", "body": "other/repo#7"}, "o/r", 7)


def test_update_suggestions_flow():
    st = {"suggestions": {
        "o/r#1": {"repo": "o/r", "number": 1, "status": "suggested", "suggested_at": iso(2)},
        "o/r#2": {"repo": "o/r", "number": 2, "status": "suggested", "suggested_at": iso(2)},
        "o/r#3": {"repo": "o/r", "number": 3, "status": "suggested", "suggested_at": iso(30)},
        "o/r#4": {"repo": "o/r", "number": 4, "status": "suggested", "suggested_at": iso(1)},
    }}
    contrib = {"prs": [{"repo": "o/r", "title": "fix", "body": "Closes #1", "status": "merged",
                        "created_at": iso(1), "url": "u"}],
               "commented_issues": ["o/r#2"]}
    gh = GitHub(transport=Fake({"repos/o/r/issues/3": {"state": "open"},
                                "repos/o/r/issues/4": {"state": "closed"}}))
    track.update_suggestions(gh, st, contrib, skip_after_days=14, now=NOW)
    s = st["suggestions"]
    assert s["o/r#1"]["status"] == "merged"
    assert s["o/r#2"]["status"] == "claimed"
    assert s["o/r#3"]["status"] == "skipped"
    assert s["o/r#4"]["status"] == "taken"
    assert s["o/r#1"]["history"][-1] == {"at": NOW.isoformat(timespec="seconds"),
                                         "from": "suggested", "to": "merged"}
