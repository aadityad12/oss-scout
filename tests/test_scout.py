# -- ranking ----------------------------------------------------------------

def issue(**kw):
    base = {"key": "duckdb/duckdb#1", "repo": "duckdb/duckdb", "number": 1, "title": "t",
            "created_at": iso(2), "label_groups": ["confirmed_bug"], "labels": ["reproduced"],
            "comments": 2, "assignees": []}
    return {**base, **kw}


def test_tier_outranks_discovery(cfg):
    repo = {"friendliness": 0.7, "language": "C++", "ai_policy": "none", "stars": 5000}
    tiered = rank.score_issue(issue(), repo, cfg, {}, now=NOW)
    found = rank.score_issue(issue(repo="nobody/thing", key="nobody/thing#1"), repo, cfg, {}, now=NOW)
    assert tiered["score"] > found["score"]
    assert found["tier"] == "Discovered"


def test_restrictive_policy_sinks(cfg):
    ok = rank.score_issue(issue(), {"friendliness": 0.7, "ai_policy": "none"}, cfg, {}, now=NOW)
    bad = rank.score_issue(issue(), {"friendliness": 0.7, "ai_policy": "restrictive"}, cfg, {}, now=NOW)
    assert bad["score"] == pytest.approx(ok["score"] * 0.6, abs=0.2)


def test_home_project_bonus(cfg):
    st = {"contributions": {"per_repo": {"duckdb/duckdb": {"merged": 2}}}}
    base = rank.score_issue(issue(), {"friendliness": 0.7}, cfg, {}, now=NOW)["score"]
    home = rank.score_issue(issue(), {"friendliness": 0.7}, cfg, st, now=NOW)["score"]
    assert home > base


def test_eligibility(cfg):
    assert rank.eligible(issue(), {}, cfg, {}, now=NOW) is None
    assert rank.eligible(issue(), {}, cfg, {"suggestions": {"duckdb/duckdb#1": {}}}, now=NOW) == "already suggested"
    assert rank.eligible(issue(assignees=["x"]), {}, cfg, {}, now=NOW) == "assigned"
    assert rank.eligible(issue(created_at=iso(400)), {}, cfg, {}, now=NOW) == "too old"
    assert rank.eligible(issue(labels=["wontfix"]), {}, cfg, {}, now=NOW).startswith("label")
    assert rank.eligible(issue(repo="a/b", key="a/b#1"), {"stars": 10}, cfg, {}, now=NOW) == "too few stars"


def test_turned_down_issues_cool_off(cfg):
    def passed(days_ago):
        return {"passed": {"duckdb/duckdb#1": {"at": iso(days_ago), "reason": "needs hardware"}}}
    assert rank.eligible(issue(), {}, cfg, passed(5), now=NOW) == "turned down recently"
    assert rank.eligible(issue(), {}, cfg, passed(61), now=NOW) is None


